/* Builds index.html (one self-contained page) from index.template.html and the source files beside it.
   Run from anywhere:  PATH=/opt/node22/bin:$PATH node build.cjs
   - inlines dashboard-canvas.css
   - inlines the ES modules in dependency order as one module script (import lines dropped, "export " dropped)
   - draws the still fallback map (inline SVG) from players/standin-mask.js
   The source files stay the real source; index.html is generated. */
'use strict';
const fs = require('fs');
const path = require('path');
const DIR = __dirname;
const read = (p) => fs.readFileSync(path.join(DIR, p), 'utf8');

const ORDER = [
  'players/player-base.js',
  'players/standin-mask.js',
  'players/lottie-player.js',
  'players/svg-player.js',
  'players/canvas-player.js',
  'players/standin-player.js',
  'dashboard-canvas.js',
  'demo.js'
];

function strip(src, file) {
  const out = src
    .replace(/^import\s[^;]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^export\s+(?=(const|let|function|async function|class)\b)/gm, '');
  if (/^\s*(import|export)\s/m.test(out)) throw new Error('Unhandled import/export left in ' + file);
  return '/* ---- ' + file + ' ---- */\n' + out.trim() + '\n';
}

/* top-level name clash guard */
const names = new Map();
const js = ORDER.map((f) => {
  const s = strip(read(f), f);
  for (const m of s.matchAll(/^(?:const|let|function|async function|class)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (names.has(m[1])) throw new Error('Name ' + m[1] + ' defined in both ' + names.get(m[1]) + ' and ' + f);
    names.set(m[1], f);
  }
  return s;
}).join('\n');

/* still map: one path of round dots (zero-length strokes with round caps) */
const maskSrc = read('players/standin-mask.js');
const mask = JSON.parse(maskSrc.slice(maskSrc.indexOf('/*MASK*/') + 8, maskSrc.indexOf('/*END*/')));
let d = '';
mask.rowsHex.forEach((hex, r) => {
  for (let i = 0; i < hex.length; i++) {
    const n = parseInt(hex[i], 16);
    for (let b = 0; b < 4; b++) if (n & (8 >> b)) {
      const c = i * 4 + b; if (c >= mask.cols) continue;
      d += 'M' + (c * mask.step + mask.step / 2) + ' ' + (r * mask.step + mask.step / 2) + 'h0';
    }
  }
});
const staticSvg = '<svg viewBox="0 0 ' + mask.w + ' ' + mask.h + '" preserveAspectRatio="none" focusable="false"><path d="' + d + '" fill="none" stroke="rgba(247,241,232,.3)" stroke-width="3.4" stroke-linecap="round"/></svg>';

let html = read('index.template.html');
html = html.replace('/*INLINE:dashboard-canvas.css*/', () => read('dashboard-canvas.css').trim());
html = html.replace('<!--INLINE:STATIC_MAP-->', () => staticSvg);
html = html.replace('/*INLINE:JS*/', () => '/* Generated by build.cjs from the source files beside this page. Edit those, then rebuild. */\n' + js.replace(/<\/script/gi, '<\\/script'));
if (/INLINE:/.test(html)) throw new Error('A marker was not replaced');
fs.writeFileSync(path.join(DIR, 'index.html'), html);
console.log('index.html', html.length, 'bytes;', names.size, 'top-level names; still map', staticSvg.length, 'bytes');
