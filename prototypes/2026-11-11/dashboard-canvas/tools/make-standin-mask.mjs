/* Build-time tool: writes players/standin-mask.js, the land grid the stand-in animation and the still map draw from.
   Uses the same world data and projection as the live chapter's h3-dash-js (world-atlas 2.0.2 countries-110m,
   d3.geoEqualEarth fitted to 960x470 with an 8px inset, Antarctica left out), so hub positions line up with the real map.
   Run once (needs world-atlas@2.0.2, topojson-client@3.1.0, d3-geo@3.1.1, d3-array@3.2.4 unpacked in one node_modules):
     node tools/make-standin-mask.mjs /path/to/node_modules
   Not loaded by the page. */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';

const NM = process.argv[2];
if (!NM) { console.error('usage: node tools/make-standin-mask.mjs /path/to/node_modules'); process.exit(1); }
const d3 = await import(pathToFileURL(join(NM, 'd3-geo/src/index.js')).href);
const topo = await import(pathToFileURL(join(NM, 'topojson-client/src/index.js')).href);
const world = JSON.parse(readFileSync(join(NM, 'world-atlas/countries-110m.json'), 'utf8'));

const W = 960, H = 470, STEP = 8, ATA = '010';
const feats = topo.feature(world, world.objects.countries).features.filter(f => f.id !== ATA);
const proj = d3.geoEqualEarth().fitExtent([[8, 8], [W - 8, H - 8]], { type: 'FeatureCollection', features: feats });
const cols = Math.floor(W / STEP), rows = Math.floor(H / STEP);
const lines = [];
let land = 0;
for (let r = 0; r < rows; r++) {
  let s = '';
  for (let c = 0; c < cols; c++) {
    const ll = proj.invert([c * STEP + STEP / 2, r * STEP + STEP / 2]);
    let hit = false;
    if (ll && isFinite(ll[0]) && isFinite(ll[1])) for (const f of feats) { if (d3.geoContains(f, ll)) { hit = true; break; } }
    s += hit ? '1' : '0';
    if (hit) land++;
  }
  lines.push(s);
}
/* hex-encode each row (4 cells per hex digit) to keep the file small */
const hexRows = lines.map(s => { let o = ''; for (let i = 0; i < s.length; i += 4) o += parseInt(s.slice(i, i + 4).padEnd(4, '0'), 2).toString(16); return o; });
const mask = { w: W, h: H, step: STEP, cols, rows, scale: +proj.scale().toFixed(6), translate: proj.translate().map(v => +v.toFixed(6)), rowsHex: hexRows };
const out = `/* GENERATED by tools/make-standin-mask.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
   Land grid (${cols} x ${rows} cells of ${STEP}px on a ${W}x${H} canvas, ${land} land cells) and the Equal Earth fit
   (scale, translate) used by the live chapter's map. Antarctica is left out, as on the live map. */
export const STANDIN_MASK = /*MASK*/${JSON.stringify(mask)}/*END*/;
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'players', 'standin-mask.js'), out);
console.log('cols', cols, 'rows', rows, 'land', land, 'scale', mask.scale, 'translate', mask.translate);
